import { NextResponse } from "next/server";

// Управление кэшем для HTML-страниц.
//
// Зачем: чтобы после деплоя люди сразу видели свежую версию сайта при
// обычном заходе/обновлении — без «очистить кэш» и Ctrl+Shift+R.
//
// Как это работает:
// - no-cache НЕ значит «не кэшировать». Значит: «храни копию, но перед показом
//   всегда спроси сервер — не изменилось ли». Если не изменилось, сервер ответит
//   304 (мгновенно, без скачивания). Если изменилось — отдаст новую страницу.
// - Тяжёлые файлы (JS/CSS/картинки из /_next/static) мы НЕ трогаем: у них в имени
//   хэш, при каждом деплое имя меняется, поэтому их можно кэшировать «вечно».
//   Свежая HTML-страница просто сошлётся на новые имена файлов.
export function middleware() {
  const response = NextResponse.next();
  response.headers.set("Cache-Control", "no-cache");
  return response;
}

export const config = {
  // Применяем только к страницам. Исключаем:
  // - _next/  — внутренние файлы сборки (статика с хэшем, кэшируется вечно)
  // - api/    — это данные, у них своя логика кэша
  // - всё с точкой в пути (.webp, .png, .json, .ico ...) — это файлы, не страницы
  matcher: ["/((?!_next/|api/|.*\\.).*)"],
};
